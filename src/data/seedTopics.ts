function splitTags(raw: string): string[] {
  return raw.split(',').map((t) => t.trim()).filter(Boolean)
}

export const SEED_FETCHED_AT = 0

export function buildSeedTopics(): TopicItem[] {
  const explanation: TopicItem[] = EXPLANATION.map(([title, prompt, tags], i) => ({
    id: `seed-exp-${String(i + 1).padStart(3, '0')}`,
    bank: 'explanation',
    title,
    prompt,
    tags: splitTags(tags),
    source: 'seed',
    fetchedAt: SEED_FETCHED_AT,
  }))
  const propositions: TopicItem[] = PROPOSITIONS.map(
    ([claim, backgroundBullets, keywords, tags], i) => ({
      id: `seed-prop-${String(i + 1).padStart(3, '0')}`,
      bank: 'proposition',
      claim,
      backgroundBullets,
      keywords,
      tags: splitTags(tags),
      source: 'seed',
      fetchedAt: SEED_FETCHED_AT,
    }),
  )
  return [...explanation, ...propositions]
}

export const SEED_COUNTS = {
  explanation: EXPLANATION.length,
  proposition: PROPOSITIONS.length,
}
